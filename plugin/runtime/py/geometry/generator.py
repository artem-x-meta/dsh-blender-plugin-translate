# Fix: module level uses _KIT directly, but previously it was defined **only inside the POSTLUDE string** ⇒ a pure python import was bound to blow up
# (on the Blender side the preload namespace leak masked it). Resolve it explicitly once here, and error clearly when it is missing.
_KIT = getattr(sys.modules.get("dsh_rt_kernel"), "dsh_kit", None)
if _KIT is None:
    raise RuntimeError("generator needs the shared kernel K.dsh_kit (injected by KERNEL_BOOTSTRAP; on the pure python path the tests inject it)")

_j = _KIT.j  # shared kernel (the original local implementation was removed)
def _kernel():
    return sys.modules.get("dsh_rt_kernel")


def _store():
    K = _kernel()
    if K is None:
        raise RuntimeError("needs the persistent kernel K (go through the blender_rt_* channel)")
    if not hasattr(K, "dsh_generator"):
        K.dsh_generator = {"runs": [], "log": []}
    return K.dsh_generator


def _now():
    return datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")


def _root(d=None):
    """generator root directory: explicit d > env DSH_GENERATOR_DIR > dsh_generators under the user's home."""
    d = d or os.environ.get("DSH_GENERATOR_DIR")
    if not d:
        d = os.path.join(os.path.expanduser("~"), "dsh_generators")
    return os.path.abspath(d)


def _paths(name, d=None):
    root = _root(d)
    safe = "".join(c if (c.isalnum() or c in "._-") else "_" for c in str(name))
    if not safe:
        raise ValueError("generator name must not be empty")
    return root, os.path.join(root, safe + ".py"), os.path.join(root, safe + ".json")


def _hash(s):
    return hashlib.md5(s.encode("utf-8")).hexdigest()[:12]


def _load_sidecar(side):
    try:
        with open(side, "r", encoding="utf-8") as fh:
            return json.load(fh)
    except Exception:
        return {}


def _save_sidecar(side, obj):
    try:
        os.makedirs(os.path.dirname(side), exist_ok=True)
        with open(side, "w", encoding="utf-8") as fh:
            json.dump(obj, fh, ensure_ascii=False, indent=1)
        return True
    except Exception:
        return False


def _blender_bin():
    """The executable of the current Blender (a generator runs in "another fresh process", used to prove reproducibility)."""
    try:
        import bpy
        p = bpy.app.binary_path
        if p and os.path.exists(p):
            return p
    except Exception:
        pass
    return shutil.which("blender") or shutil.which("blender.exe")


# ---------------------------------------------------------------- registry

def generator_save(name, code, params=None, note="", dir=None, overwrite=True):
    """Save a generator (source + sidecar metadata). Once the source changes, the previous run receipt counts as expired."""
    if not code or not str(code).strip():
        return _j({"ok": False, "error": "code is empty: an empty generator must fail (silent empty output is a hard red line in this project)"})
    try:
        root, path, side = _paths(name, dir)
    except Exception as e:
        return _j({"ok": False, "error": str(e)})
    old = None
    if os.path.exists(path):
        try:
            with open(path, "r", encoding="utf-8") as fh:
                old = fh.read()
        except Exception:
            old = None
        if old is not None and old != code and not overwrite:
            return _j({"ok": False, "error": "a generator with the same name already exists with different content; pass overwrite=true to replace it",
                       "path": path, "hash_old": _hash(old), "hash_new": _hash(code)})
    os.makedirs(root, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(code)
    side_data = _load_sidecar(side)
    meta = {"name": str(name), "params": params or {}, "note": str(note),
            "hash": _hash(code), "bytes": len(code), "saved_at": _now(), "path": path,
            "last_run": side_data.get("last_run")}
    _save_sidecar(side, meta)
    st = _store()
    st["log"].append({"t": _now(), "action": "save", "name": str(name), "hash": meta["hash"]})
    del st["log"][:-200]
    stale = bool(meta.get("last_run") and meta["last_run"].get("hash") != meta["hash"])
    return _j({"ok": True, "name": str(name), "path": path, "sidecar": side, "hash": meta["hash"],
               "bytes": len(code), "last_run_becomes_stale": stale,
               "note": "source changed → the previous run receipt is stale (that is the definition of \"unverified\"); for a green light reproduce it with generator_run" if stale else ""})


def generator_list(dir=None):
    root = _root(dir)
    out = []
    try:
        names = sorted(os.listdir(root))
    except Exception:
        names = []
    for n in names:
        if not n.endswith(".py"):
            continue
        base = n[:-3]
        side = os.path.join(root, base + ".json")
        meta = _load_sidecar(side)
        cur = None
        try:
            with open(os.path.join(root, n), "r", encoding="utf-8") as fh:
                cur = _hash(fh.read())
        except Exception:
            pass
        lr = meta.get("last_run") or {}
        out.append({"name": base, "hash_now": cur, "hash_last_run": lr.get("hash"),
                    "stale": bool(lr and cur and lr.get("hash") != cur),
                    "verdict": lr.get("verdict"), "last_run_at": lr.get("t"),
                    "objects": (lr.get("receipt") or {}).get("objects"),
                    "note": meta.get("note")})
    return _j({"ok": True, "root": root, "count": len(out), "generators": out,
               "rule": "stale=true means the source was edited after the last run → that receipt can no longer be used as evidence"})


def generator_get(name, dir=None):
    try:
        root, path, side = _paths(name, dir)
    except Exception as e:
        return _j({"ok": False, "error": str(e)})
    if not os.path.exists(path):
        return _j({"ok": False, "error": "generator does not exist: %s" % name, "looked_at": path})
    with open(path, "r", encoding="utf-8") as fh:
        code = fh.read()
    meta = _load_sidecar(side)
    return _j({"ok": True, "name": str(name), "path": path, "hash": _hash(code), "bytes": len(code),
               "code": code, "meta": meta,
               "stale": bool((meta.get("last_run") or {}).get("hash") and (meta["last_run"].get("hash") != _hash(code)))})


def generator_diff(name, dir=None):
    """Source vs the source at the last run: changed or not (changed → the previous receipt is stale)."""
    try:
        root, path, side = _paths(name, dir)
    except Exception as e:
        return _j({"ok": False, "error": str(e)})
    if not os.path.exists(path):
        return _j({"ok": False, "error": "generator does not exist: %s" % name})
    with open(path, "r", encoding="utf-8") as fh:
        code = fh.read()
    meta = _load_sidecar(side)
    lr = meta.get("last_run") or {}
    if not lr:
        return _j({"ok": True, "name": str(name), "hash_now": _hash(code), "last_run": None,
                   "changed": None, "verdict": "unresolved",
                   "note": "never run → nothing to compare against; call generator_run first to establish a baseline"})
    changed = lr.get("hash") != _hash(code)
    return _j({"ok": True, "name": str(name), "hash_now": _hash(code), "hash_last_run": lr.get("hash"),
               "changed": changed, "last_run_at": lr.get("t"), "last_verdict": lr.get("verdict"),
               "verdict": "refuted" if changed else "supported",
               "note": "source changed → the previous receipt is stale, a re-run is required" if changed else "identical to the last run"})


# ---------------------------------------------------------------- compile gate: reproduce in a fresh process

def _check_expect(receipt, expect):
    """Compare the receipt against the expectation → (verdict, why[]). expect supports objects/names/min_objects/max_objects/max_tris."""
    if not expect:
        return "unresolved", ["no expect given: only \"it runs\" was proved, not \"what it produces is what you want\""]
    why, bad = [], []
    if "objects" in expect and int(receipt.get("objects") or -1) != int(expect["objects"]):
        bad.append("objects measured %s ≠ expected %s" % (receipt.get("objects"), expect["objects"]))
    if "min_objects" in expect and int(receipt.get("objects") or -1) < int(expect["min_objects"]):
        bad.append("objects measured %s < min %s" % (receipt.get("objects"), expect["min_objects"]))
    if "max_objects" in expect and int(receipt.get("objects") or 10 ** 9) > int(expect["max_objects"]):
        bad.append("objects measured %s > max %s" % (receipt.get("objects"), expect["max_objects"]))
    if "max_tris" in expect and int(receipt.get("tris") or 0) > int(expect["max_tris"]):
        bad.append("tris measured %s > max %s" % (receipt.get("tris"), expect["max_tris"]))
    if "names" in expect:
        want = [str(x) for x in expect["names"]]
        got = [str(x) for x in (receipt.get("names") or [])]
        miss = [n for n in want if n not in got]
        if miss:
            bad.append("missing expected objects: %s (measured %d: %s)" % (", ".join(miss[:6]), len(got), ", ".join(got[:8])))
    if receipt.get("receipt_error"):
        bad.append("the receipt itself reports an error: %s" % receipt["receipt_error"])
    if bad:
        return "refuted", bad
    why.append("all expectations met: %s" % json.dumps({k: receipt.get(k) for k in ("objects", "tris") if k in receipt},
                                              ensure_ascii=False))
    return "supported", why


def generator_run(name, args=None, dir=None, expect=None, engine="none", factory_startup=True,
                  use_cache=True, timeout_ms=180000, keep_dir=None, clean_scene=True):
    """Compile gate: run this generator from scratch in a **fresh headless Blender process**, produce a receipt and compare it against expect.

    Cache: when neither the source hash nor the args hash changed and the last verdict was supported → return the previous receipt directly (cached=true).
    """
    try:
        root, path, side = _paths(name, dir)
    except Exception as e:
        return _j({"ok": False, "error": str(e)})
    if not os.path.exists(path):
        return _j({"ok": False, "error": "generator does not exist: %s" % name, "looked_at": path})
    with open(path, "r", encoding="utf-8") as fh:
        code = fh.read()
    h = _hash(code)
    ah = _hash(json.dumps(args or {}, sort_keys=True, ensure_ascii=False))
    meta = _load_sidecar(side)
    lr = meta.get("last_run") or {}
    if use_cache and lr and lr.get("hash") == h and lr.get("args_hash") == ah and lr.get("verdict") == "supported":
        return _j({"ok": True, "cached": True, "name": str(name), "hash": h, "args_hash": ah,
                   "verdict": lr.get("verdict"), "receipt": lr.get("receipt"), "ms": 0,
                   "note": "neither the source nor the parameters changed and the last run passed the gate → cache hit (no re-run without a change, this is the \"module-level cache\")"})
    exe = _blender_bin()
    if not exe:
        return _j({"ok": False, "error": "no blender executable found (bpy.app.binary_path is empty)"})
    tmpdir = keep_dir or tempfile.mkdtemp(prefix="dsh_gen_")
    os.makedirs(tmpdir, exist_ok=True)
    run_py = os.path.join(tmpdir, "_dsh_generator_run.py")
    with open(run_py, "w", encoding="utf-8") as fh:
        fh.write("# assembled by generator_run: prelude + your source + postlude\n")
        fh.write(PRELUDE)
        fh.write("\n# ---- generator source (%s / %s)----\n" % (name, h))
        fh.write(code)
        fh.write("\n")
        fh.write(POSTLUDE)
    cmd = [exe, "-b"]
    if factory_startup:
        cmd.append("--factory-startup")
    if engine and engine != "none":
        cmd += ["--python-expr", "import bpy;bpy.context.scene.render.engine=%s" % json.dumps(engine)]
    cmd += ["--python", run_py, "--", json.dumps(args or {}, ensure_ascii=False),
            "1" if clean_scene else "0"]
    t0 = time.time()
    try:
        p = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                           timeout=max(5, int(timeout_ms) / 1000.0))
        out = p.stdout.decode("utf-8", "ignore")
        err = p.stderr.decode("utf-8", "ignore")
        rc = p.returncode
    except subprocess.TimeoutExpired:
        out, err, rc = "", "timeout after %sms" % timeout_ms, -9
    except Exception as e:
        out, err, rc = "", "%s: %s" % (type(e).__name__, str(e)[:200]), -1
    ms = int((time.time() - t0) * 1000)
    receipt = None
    for line in out.splitlines():
        if line.startswith("DSH_RECEIPT "):
            try:
                receipt = json.loads(line[len("DSH_RECEIPT "):])
            except Exception:
                receipt = None
    script_error = bool(re.search(r"Traceback \(most recent call last\)|(^|\n)\s*\w*Error:", err or ""))
    if rc != 0 or receipt is None or script_error:
        verdict = "refuted"
        why = ["process exit=%s" % rc]
        if receipt and receipt.get("receipt_error"):
            why.append("the receipt reports an error: %s" % receipt["receipt_error"])
        if err.strip():
            why.append("stderr tail: %s" % err.strip()[-500:])
        elif receipt is None:
            why.append("no receipt (the script may not have reached the postlude)")
        if script_error and rc == 0:
            why.append("measured pitfall: when a Blender --python script raises, **the exit code is still 0** → the verdict therefore uses \"receipt + stderr error markers\","
                       "checking only exit would miss it")
        result = {"ok": True, "cached": False, "name": str(name), "hash": h, "args_hash": ah, "ms": ms,
                  "exit": rc, "verdict": verdict, "why": why, "receipt": receipt,
                  "stdout_tail": out.strip()[-800:], "stderr_tail": err.strip()[-800:],
                  "script": run_py, "timeout_ms": timeout_ms,
                  "note": "the compile gate failed (not running through does not count). The script and logs are left at the path above, for debugging."}
        lr0 = meta.get("last_run")
        if not isinstance(lr0, dict):
            lr0 = {}
        lr0.update({"hash": h, "args_hash": ah, "verdict": verdict,
                    "t": _now(), "ms": ms, "receipt": receipt})
        meta["last_run"] = lr0
        _save_sidecar(side, meta)
        return _j(result)
    verdict, why = _check_expect(receipt, expect)
    meta["last_run"] = {"hash": h, "args_hash": ah, "verdict": verdict, "t": _now(), "ms": ms,
                        "receipt": receipt, "expect": expect}
    _save_sidecar(side, meta)
    st = _store()
    st["runs"].append({"t": _now(), "name": str(name), "hash": h, "verdict": verdict, "ms": ms})
    del st["runs"][:-200]
    return _j({"ok": True, "cached": False, "name": str(name), "hash": h, "args_hash": ah, "ms": ms,
               "exit": rc, "verdict": verdict, "why": why, "receipt": receipt, "script": run_py,
               "expect": expect, "timeout_ms": timeout_ms,
               "note": ("Three states: " "supported=expectation met; refuted=expectation not met (the differences are listed in why);"
                        "unresolved=no expect given, only that it runs was proved, not that it runs correctly")})


