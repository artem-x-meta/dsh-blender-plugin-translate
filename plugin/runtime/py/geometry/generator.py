# -*- coding: utf-8 -*-
"""Generator registry (v0.9.0 · the lightweight Blender-native version of Procedura's "code-modelling channel", integration batch 3 #18).

Why it exists (and how it relates to upstream)
------------------------------------------------------------------------------
Procedura's core benefit is not "using OpenSCAD" but **the program is the shape**:
  ① the model is generated by a program that is readable, diffable and replayable;
  ② the product counts only once it passes the "compile gate" (the program must run end to end);
  ③ module-level cache: no re-run while the source is unchanged;
  ④ as soon as the source changes, the previous verification result expires immediately.
Upstream uses OpenSCAD + Manifold as the geometry kernel (**Manifold is mandatory**: measured in practice, the same hull() took CGAL 1774 s
vs Manifold 1.77 s). This plugin takes the bpy-native route and neither side has OpenSCAD installed on the user's machine — so here
①–④ are obtained the Blender-native way: **a generator = a python program** (bpy/bmesh/mathutils, anything goes),
run once from scratch in a **fresh headless process** to prove reproducibility, with the product written out as a receipt and the source hash as the cache key.

Boundaries (stated honestly)
  * the geometry kernel is still Blender (CSG via bpy's boolean/hull and the like), **not** Manifold; large boolean operations
    are much slower than Manifold — that is the price of not having OpenSCAD installed, not something that could be done and was left out.
  * a generator runs in a **separate process** (--factory-startup), so it cannot see the transient state of your current GUI session —
    which is exactly the definition of "reproducible", but it also means generator code must not depend on the K of a session.

Entry points (tool-side ops, prefix generator_)
    blender_rt_plan(op="generator_save", args={name, code, params, note, overwrite})
    blender_rt_plan(op="generator_run",  args={name, args, expect, engine, use_cache, timeout_ms})
    blender_rt_plan(op="generator_list") / generator_get / generator_diff / generator_help
    blender_rt_plan(op="generator_selftest")

Program contract (how to write a generator script)
    * the variable PARAMS: dict (from --args; whatever run passes is what you get).
    * it is recommended to end with print("DSH_RECEIPT " + json.dumps({...})); printing is optional — the runner scans the scene
      and produces a receipt itself (object count / names / triangle count / bbox), so "a silent script" never becomes "no evidence".
    * a non-zero exit code or a raised exception → ok:false straight away, with the stderr tail carried back (no silent success).
"""
