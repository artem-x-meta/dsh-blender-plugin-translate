def generator_selftest():
    """Synthetic self-test: save → run through (supported) → cache hit → expectation not met (refuted) → edit the source (stale) → broken script (refuted)."""
    tmp = tempfile.mkdtemp(prefix="dsh_gen_selftest_")
    ok_all, steps = True, []
    try:
        code = "\n".join([
            "# self-test generator: place a few cubes according to PARAMS",
            "n = int(PARAMS.get('n', 3))",
            "size = float(PARAMS.get('size', 1.0))",
            "for i in range(n):",
            "    bpy.ops.mesh.primitive_cube_add(size=size, location=(i * 1.5, 0, 0))",
            "    bpy.context.object.name = 'GEN_CUBE_%02d' % i",
            "print('DSH_RECEIPT ' + json.dumps({'made': n, 'size': size}))",
        ])
        r1 = json.loads(generator_save("selftest_cubes", code, {"n": 3, "size": 1.0}, "selftest", dir=tmp))
        steps.append({"step": "save", "ok": r1.get("ok"), "hash": r1.get("hash")})
        ok_all &= bool(r1.get("ok"))

        a1 = json.loads(generator_run("selftest_cubes", {"n": 3, "size": 1.0},
                                      dir=tmp, expect={"objects": 3, "names": ["GEN_CUBE_00", "GEN_CUBE_02"]},
                                      timeout_ms=120000))
        steps.append({"step": "run(expect ok)", "verdict": a1.get("verdict"), "objects": (a1.get("receipt") or {}).get("objects"),
                      "ms": a1.get("ms"), "cached": a1.get("cached"), "why": a1.get("why")})
        ok_all &= (a1.get("verdict") == "supported" and (a1.get("receipt") or {}).get("objects") == 3)

        a1b = json.loads(generator_run("selftest_cubes", {"n": 3, "size": 1.0}, dir=tmp,
                                       expect={"objects": 3}, timeout_ms=120000))
        steps.append({"step": "run again (cache)", "cached": a1b.get("cached"), "ms": a1b.get("ms"),
                      "verdict": a1b.get("verdict")})
        ok_all &= (a1b.get("cached") is True and a1b.get("ms") == 0)

        a2 = json.loads(generator_run("selftest_cubes", {"n": 5, "size": 1.0}, dir=tmp,
                                      expect={"objects": 3}, timeout_ms=120000))
        steps.append({"step": "run(expect mismatch)", "verdict": a2.get("verdict"), "objects": (a2.get("receipt") or {}).get("objects"),
                      "why": a2.get("why")})
        ok_all &= (a2.get("verdict") == "refuted")

        a3 = json.loads(generator_run("selftest_cubes", {"n": 5, "size": 1.0}, dir=tmp,
                                      engine="none", timeout_ms=120000))
        steps.append({"step": "run(no expect)", "verdict": a3.get("verdict"),
                      "why": (a3.get("why") or [""])[0][:80]})
        ok_all &= (a3.get("verdict") == "unresolved")

        r2 = json.loads(generator_save("selftest_cubes", code.replace("1.5", "2.0"), {"n": 3}, "edited", dir=tmp))
        d = json.loads(generator_diff("selftest_cubes", dir=tmp))
        steps.append({"step": "save(overwrite)+diff", "stale_after_edit": r2.get("last_run_becomes_stale"),
                      "diff_changed": d.get("changed"), "diff_verdict": d.get("verdict")})
        ok_all &= (d.get("changed") is True and d.get("verdict") == "refuted")

        bad = json.loads(generator_save("selftest_bad", "def broken(:\n    pass\n", dir=tmp))
        b1 = json.loads(generator_run("selftest_bad", dir=tmp, timeout_ms=120000))
        steps.append({"step": "bad script", "save_ok": bad.get("ok"), "verdict": b1.get("verdict"),
                      "exit": b1.get("exit"), "stderr": (b1.get("stderr_tail") or "")[-120:],
                      "exit_code_reliable": False,
                      "why_note": "measured: when Blender --python raises, exit is still 0 → the criterion uses a missing receipt + stderr error markers"})
        ok_all &= (b1.get("verdict") == "refuted" and "SyntaxError" in (b1.get("stderr_tail") or "")
                   and (b1.get("why") and any("exit code is still 0" in w for w in b1["why"])))

        lst = json.loads(generator_list(dir=tmp))
        steps.append({"step": "list", "count": lst.get("count")})
        ok_all &= (lst.get("count") == 2)
        return _j({"ok": bool(ok_all), "steps": steps, "tmp": tmp,
                   "expect": "save ok → run 3 cubes supported → run again hits the cache (ms=0) → expectation mismatch refuted → "
                             "no expect unresolved → after editing the source diff.changed=true/verdict=refuted → "
                             "broken script refuted (stderr carries SyntaxError, and the criterion does not rely on exit — Blender's exit code on an exception is 0) → "
                             "list counts 2"})
    except Exception as e:
        import traceback
        return _j({"ok": False, "error": "%s: %s" % (type(e).__name__, str(e)[:300]),
                   "traceback": traceback.format_exc()[-900:], "steps": steps})


def generator_dispatch(op, args=None):
    """Single entry point: the tool side sends {"op": …, "args": {…}} (the envelope is already stripped by the engine; this is a second safeguard).

    v0.9.6 fix: the old implementation **flattened the payload's `args` key unconditionally** into kwargs:

        for k, v in (args or {}).items():
            if k == "args" and isinstance(v, dict):
                kw.update(v)      # ← this line

    That is fine for other ops (they have no parameter called args), but `generator_run(name, args, …)`'s
    **args IS the generator PARAMS**: one `{"name":"x","args":{"n":3}}` was flattened into
    `generator_run(name="x", n=3)` — args disappears (PARAMS becomes an empty {}), n becomes an unknown parameter,
    and you get either a TypeError or a silent run with empty parameters producing a result that "runs but is wrong". That is exactly how it was hit in the field.

    Current semantics (two rules, neither of which loses information):
      · op == "run"      → `args` are **real parameters**, passed down as is, never flattened;
      · other ops        → unwrap the envelope only when `args` is the **only key** (backwards compatible with old calls),
                           otherwise leave it as is (rather reply "parameter mismatch + help" than guess).
    """
    if isinstance(args, str):
        try:
            args = json.loads(args) if args.strip() else {}
        except Exception:
            args = {}
    raw = dict(args or {}) if isinstance(args, dict) else {}
    opname = str(op)
    if opname != "run" and set(raw.keys()) == {"args"} and isinstance(raw.get("args"), dict):
        raw = dict(raw["args"])
    ops = {"save": generator_save, "run": generator_run, "list": generator_list, "get": generator_get,
           "diff": generator_diff, "help": generator_help, "selftest": generator_selftest}
    fn = ops.get(opname)
    if fn is None:
        return _j({"ok": False, "error": "unknown generator op", "op": op, "ops": sorted(ops)})
    try:
        return fn(**raw)
    except TypeError as e:
        return _j({"ok": False, "error": "parameter mismatch: %s" % str(e)[:200], "op": opname,
                   "expected": {"save": "name, code, params, note, dir, overwrite",
                                "run": "name, args(=dict of the generator PARAMS), expect, dir, engine, use_cache, timeout_ms",
                                "list": "dir", "get": "name, dir", "diff": "name, dir"}.get(opname),
                   "note": "generator_run's parameter is named args (nested one level); it does not flatten PARAMS to the top level",
                   "help": generator_help()})


